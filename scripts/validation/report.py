def pct(x: float | None, d: int = 1) -> str:
    if x is None:
        return "—"
    return f"{100 * x:.{d}f}%".replace(".", ",")


def num(x: float | None, d: int = 3) -> str:
    if x is None:
        return "—"
    return f"{x:.{d}f}".replace(".", ",")


def ci(v: list[float]) -> str:
    return f"{num(v[0], 2)}–{num(v[1], 2)}"


def kappa_word(k: float) -> str:
    """Словесная шкала Лэндиса — Коха."""
    if k > 0.8:
        return "почти полное согласие"
    if k > 0.6:
        return "существенное согласие"
    if k > 0.4:
        return "умеренное согласие"
    if k > 0.2:
        return "слабое согласие"
    return "согласия почти нет"


